# Honeypot ethics taxonomy - content (version 0.1, "basic" taxonomy from Meeting 12)
# Each risk follows the Paper 3 pattern: definition -> how it appears in honeypots -> mitigations -> trade-off.
# 'codes' link the risk to the 69-code codebook (evidence quotes come from the final open coding).
# 'indicator' is a rule on the dataset (v3.1) that counts the entries where the risk is present or unaddressed.

STAGES = [
    ('S1', 'Design', 'Planning the study or tool: goals, what data is needed, ethics review, legal basis and how deception is justified.'),
    ('S2', 'Development', 'Building the honeypot: emulation versus real systems, LLM back ends, containment mechanisms and logging.'),
    ('S3', 'Deployment', 'Placing the honeypot: Internet exposure, hosting provider, network location, notice banners and jurisdiction.'),
    ('S4', 'Operation', 'Running the honeypot: interaction with attackers, data capture, automated responses and monitoring of containment.'),
    ('S5', 'Data handling', 'Storing, processing, enriching and sharing collected data: minimization, retention, third-party services.'),
    ('S6', 'Dissemination', 'Publishing papers, datasets and tools: data release, disclosure, distribution to other operators.'),
]

CATEGORIES = [
    ('C1', 'Human subjects and oversight', 'Whether the people behind the attacks (and anyone else affected) are treated as research subjects: ethics review, consent, notice and who is responsible.'),
    ('C2', 'Data collection and privacy', 'What personal or sensitive data the honeypot captures, about attackers, victims, users or the operator.'),
    ('C3', 'Data governance', 'How collected data is limited, kept, shared and released.'),
    ('C4', 'Harm and containment', 'Whether the honeypot can harm third parties, real systems or the physical world, and how that is prevented.'),
    ('C5', 'Deception', 'The ethics of deceiving attackers, including active, physical-world and LLM-generated deception.'),
    ('C6', 'Legal and jurisdiction', 'The legal basis for collection and interaction across jurisdictions, regulation and disclosure duties.'),
]

